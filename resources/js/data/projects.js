export const getProjectImage = (project) => {
    if (project.image && project.image.startsWith('http')) {
        return project.image;
    }

    if (project.imageId) {
        return `https://images.unsplash.com/photo-${project.imageId}?auto=format&fit=crop&q=80&w=800`;
    }

    const keywords = project.keywords ?? 'university';
    return `https://loremflickr.com/800/600/technology,${keywords}/all`;
};
